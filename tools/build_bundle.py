#!/usr/bin/env python3
"""tools/build_bundle.py -- concatenate the game's modules into one runnable
script for JavaScriptCore, with a caller-supplied probe appended.

Every headless probe in this repo needs the same thing: the real src/*.js in
index.html's load order, the host stubs from tools/playtest.py, then the probe.

It is written as a tool rather than inlined into each probe for one specific
reason. An earlier version of these probes generated the bundle once and then
re-ran the same generated file after editing src/hazards.js. The bundle
EMBEDDS THE SOURCE TEXT, so every "after the fix" measurement was quietly
re-measuring the code from before the fix -- which is how a density change that
provably did not alter the output got reported as having altered it. A probe
that can outlive its own source edit is worse than no probe.

    python3 tools/build_bundle.py <probe.js> <out.js>
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "tools"))

import playtest  # noqa: E402


def build(probe_js: str) -> str:
    parts = [
        "// GENERATED by tools/build_bundle.py -- do not edit, regenerate instead.",
        "var __RUNS=1, __SEED=1;",
        "var __MANIFEST = %s;" % json.dumps(
            (ROOT / "src/sprites/manifest.json").read_text()),
        "var __DIMS = %s;" % json.dumps(playtest.sprite_dims()),
        "var __ERRORS = [];",
        "var __STATS = { frames:0, drawCalls:0, simTicks:0, hops:0, stages:0,"
        " deaths:0, wins:0, nan:0 };",
        playtest.PRELUDE_JS,
        'function nowMs(){ return (new Date()).getTime(); }',
    ]
    for rel in playtest.MODULES:
        parts.append("\n// ===== %s =====\n%s" % (rel, (ROOT / rel).read_text()))
    parts.append(probe_js)
    return "\n".join(parts)


def main() -> int:
    if len(sys.argv) < 3:
        print(__doc__)
        return 2
    probe = Path(sys.argv[1])
    out = Path(sys.argv[2])
    if not probe.is_absolute():
        probe = ROOT / probe
    out.write_text(build(probe.read_text()))
    print("bundle written: %s (%d bytes)" % (out, out.stat().st_size))
    return 0


if __name__ == "__main__":
    sys.exit(main())