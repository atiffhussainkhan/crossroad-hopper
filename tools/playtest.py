#!/usr/bin/env python3
"""tools/playtest.py -- play the real game headlessly, N times, and report.

This is not a smoke test of a reimplementation. It concatenates the game's own
src/*.js, loads it into JavaScriptCore or Node, and drives the shipped code:

  * SIMULATION -- SimCore.createGame() -> tick()/hop() to stage completion, with
    random characters, random seeds and randomised input timing, so the
    collision, pursuer, hazard-reach and phase-transition code all execute.
  * RENDER     -- Scene.renderScene() + CharacterRenderer.drawCharacter() every
    frame against a recording canvas stub, for every roster character. The stub
    throws on a NaN/Infinity coordinate, because a canvas silently drops a draw
    call given NaN and that is precisely how a character goes invisible with no
    error anywhere in the log.
  * SPRITES    -- SpriteSheets.load()/frame() so the manifest and every roster
    image are resolved through the real loader.

Modules are concatenated in the order index.html loads them, because sim-core
reads Stages' constants at definition time.

    python3 tools/playtest.py [runs]        # default 10
"""

