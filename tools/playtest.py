# Pixel dimensions of every roster sprite, read off disk and handed to the stub
# Image so SpriteSheets.frame() computes real draw rectangles. Without this the
# frame path silently returns null and the render test proves nothing.


def sprite_dims() -> dict:
    out = {}
    sys.path.insert(0, str(ROOT / "tools"))
    try:
        from PIL import Image  # noqa: PLC0415
    except ImportError:
        return out
    man = json.loads((ROOT / "src/sprites/manifest.json").read_text())
    for e in man.get("characters24", []):
        p = ROOT / "assets/characters" / e["file"]
        if p.exists():
            with Image.open(p) as im:
                out[e["file"]] = [im.width, im.height]
    for name, anims in man.get("characters", {}).items():
        for anim, spec in anims.items():
            p = ROOT / "src/sprites" / name / spec["file"]
            if p.exists():
                with Image.open(p) as im:
                    out[name + "/" + spec["file"]] = [im.width, im.height]
    return out


def build_harness(dims: dict, runs: int, seed: int) -> str:
    manifest = (ROOT / "src/sprites/manifest.json").read_text()
    parts = []
    parts.append("// ---- generated by tools/playtest.py -- do not edit ----")
    parts.append("var __RUNS = %d, __SEED = %d;" % (runs, seed))
    parts.append("var __MANIFEST = %s;" % json.dumps(manifest))
    parts.append("var __DIMS = %s;" % json.dumps(dims))
    parts.append("var __MAIN_JS = %s;" % json.dumps((ROOT / "src/main.js").read_text()))
    parts.append("var __ERRORS = [];")
    parts.append("var __STATS = { frames: 0, drawCalls: 0, simTicks: 0, "
                 "hops: 0, stages: 0, deaths: 0, wins: 0, nan: 0 };")
    # The host stubs must exist BEFORE the modules load: sprite.js binds to the
    # XMLHttpRequest/Image globals when it runs, not when it is called.
    parts.append(PRELUDE_JS)

    for rel in MODULES:
        src = (ROOT / rel).read_text()
        parts.append("\n// ===== %s =====\n%s" % (rel, src))

    # main.js is evaluated by the harness via new Function(), NOT concatenated:
    # concatenated it would run before the harness had installed its DOM, and
    # it is an IIFE with no exports, so concatenation would only be a way to
    # fire it too early.

    parts.append(HARNESS_JS)
    return "\n".join(parts)


