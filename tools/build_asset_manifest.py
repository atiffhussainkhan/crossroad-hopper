#!/usr/bin/env python3
"""tools/build_asset_manifest.py — generate ASSET-MANIFEST.md for this game.

Why this exists: a second coding agent (Cursor, Cline) has no memory of this
session and no idea the roster sprites are WebP with a hard alpha channel, or
that src/stages.js is the single source of truth for what each stage looks like.
It will guess otherwise, and guessing is how "the character has a grey box
behind it" survives three rounds of fixes.

Everything here is READ from the repository at generation time. Nothing is
typed in by hand, so the manifest cannot drift from the code the way a
hand-written one will.
"""

from __future__ import annotations

import json
import os
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "ASSET-MANIFEST.md"

try:
    from PIL import Image
except ImportError:
    Image = None


def png_size(p: Path):
    """Read dimensions from the file header without loading the image."""
    try:
        with Image.open(p) as im:
            return im.width, im.height, im.mode
    except Exception:                                           # noqa: BLE001
        return None


def main() -> int:
    lines = []
    w = lines.append

    w("# Asset Manifest")
    w("")
    w("> Generated by `tools/build_asset_manifest.py`. **Do not hand-edit** —")
    w("> regenerate with `python3 tools/build_asset_manifest.py`.")
    w("> Every agent working on this game should read this before touching art.")
    w("")

    # ---- loading contract -------------------------------------------------
    w("## Load order is load-bearing")
    w("")
    w("Vanilla ES5-ish JS, no bundler, no npm, no build step. Modules are loaded")
    w("by `<script src>` in this exact order and **must not be reordered**:")
    w("")
    html = (ROOT / "index.html").read_text()
    for m in re.finditer(r'<script src="([^"]+)"', html):
        w("  %d. `%s`" % (len(re.findall(r'<script src=', html[:m.start()])) + 1, m.group(1)))
    w("")
    w("Adding a module means editing **both** `index.html` and `MODULES` in")
    w("`tools/playtest.py`, or the headless gate will not see it.")
    w("")

    # ---- rendering --------------------------------------------------------
    main_js = (ROOT / "src/main.js").read_text()
    ctx = re.search(r'getContext\(["\']([^"\']+)["\']\)', main_js)
    w("## Rendering")
    w("")
    w("  context : `getContext(\"%s\")`" % (ctx.group(1) if ctx else "?"))
    w("  dpr     : device-pixel-ratio scaled transform (see src/main.js)")
    w("")
    w("**This is an isometric 2D canvas renderer. It is not 3D.** `Iso.projectS()`")
    w("returns `[x, y]` — two numbers. A `.glb` cannot be drawn here. Before")
    w("importing any 3D asset, run:")
    w("")
    w("```")
    w("python3 /Users/mac/.minimax/asset-library/tools/gamekit.py doctor .")
    w("```")
    w("")

    # ---- roster sprites ---------------------------------------------------
    w("## Roster sprites — 24 characters")
    w("")
    man = json.loads((ROOT / "src/sprites/manifest.json").read_text())
    w("| id | file | size | alpha |")
    w("|---|---|---|---|")
    for e in man.get("characters24", []):
        p = ROOT / "assets/characters" / e["file"]
        info = png_size(p) if Image else None
        if info:
            w("| `%s` | `%s` | %dx%d | %s |"
              % (e["id"], e["file"], info[0], info[1],
                 "yes" if "A" in info[2] or info[2] == "RGBA" else "no"))
        else:
            w("| `%s` | `%s` | — | — |" % (e["id"], e["file"]))
    w("")
    w("WebP, hard alpha, **cropped so the character fills the frame**. `drawH: 46`")
    w("in `src/render/sprite.js` means *the character* is 46px tall, not 46px of")
    w("canvas. Rebuild from source JPGs with:")
    w("")
    w("```")
    w("python3 tools/build_character_pngs.py")
    w("```")
    w("")

    # ---- animated sheets --------------------------------------------------
    anim = man.get("characters", {})
    if anim:
        w("## Animated sheets")
        w("")
        w("| set | animations | frames | file |")
        w("|---|---|---|---|")
        for name, spec in anim.items():
            for aname, s in spec.items():
                p = ROOT / "src/sprites" / name / s.get("file", "")
                fr = s.get("frames") or s.get("frameCount") or "?"
                w("| %s | %s | %s | `%s` |"
                  % (name, aname, fr, s.get("file", "?")))
        w("")

    # ---- stage art --------------------------------------------------------
    art = sorted((ROOT / "art").glob("*.png"))
    if art:
        w("## Stage reference art")
        w("")
        w("Generated by `tools/render_art.py` from `src/stages.js`, and")
        w("`tools/check_art_assets.py` asserts they stay in step with it.")
        w("")
        for p in art:
            info = png_size(p) if Image else None
            if info:
                w("  %-34s %dx%d" % (p.name, info[0], info[1]))
        w("")

    # ---- hazards ----------------------------------------------------------
    w("## Hazard art is drawn procedurally")
    w("")
    w("No sprite files. `src/hazards.js` defines `KINDS` (car, taxi, log, train,")
    w("bird, pit, geyser, sinkhole…) and `src/render/scene.js` draws them with")
    w("canvas paths. Adding a new vehicle means editing `KINDS`, not dropping in")
    w("an image.")
    w("")

    # ---- where art comes from --------------------------------------------
    w("## Where to get more art")
    w("")
    w("**`/Users/mac/.minimax/asset-library/`** — 114,852 indexed 2D images and")
    w("1,909 3D models. Query it:")
    w("")
    w("```")
    w("L=/Users/mac/.minimax/asset-library")
    w("python3 $L/tools/gamekit.py doctor .        # what can this renderer show?")
    w("python3 $L/tools/image_search.py <terms>")
    w("python3 $L/tools/gamekit.py sheet scenery  # contact sheet of real pictures")
    w("```")
    w("")
    w("**Licensing:** all 114,852 2D records are `unverified` — do not")
    w("redistribute. 29 of 30 top-level packs are CC0-1.0 or MIT and are safe to")
    w("ship. Four user-supplied archives are excluded entirely; that is a rights")
    w("decision for the owner, not for an agent.")
    w("")
    w("**Do not generate placeholder art** when the library holds something")
    w("suitable. Report \"not in library\" instead — that is a better outcome than")
    w("a pretty wrong answer.")
    w("")

    # ---- verification -----------------------------------------------------
    w("## Before you commit")
    w("")
    w("```")
    w("python3 tools/playtest.py 10")
    w("```")
    w("")
    w("Requires `RESULT: NO ERRORS`, `24/24` sprites resolved, `main.js booted`,")
    w("and a **non-zero** forward-only clear rate. A zero there means a lane has")
    w("become unclearable.")
    w("")

    OUT.write_text("\n".join(lines) + "\n")
    print("wrote %s (%d lines)" % (OUT, len(lines)))
    return 0


if __name__ == "__main__":
    sys.exit(main())