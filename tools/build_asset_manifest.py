#!/usr/bin/env python3
"""Generate the legacy fallback inventory in ASSET-MANIFEST.md.

Why this exists: a second coding agent (Cursor, Cline) has no memory of this
session and no idea the roster sprites are WebP with a hard alpha channel, or
that src/stages.js is the single source of truth for what each stage looks like.
It will guess otherwise, and guessing is how "the character has a grey box
behind it" survives three rounds of fixes.

Script paths and image dimensions are read from the repository at generation
time. Current 3D model mapping lives in assets/models/manifest.json; this
inventory retains the older sprite pipeline and historical reference images.
"""

from __future__ import annotations

import json
import os
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "ASSET-MANIFEST.md"

try:
    from PIL import Image
except ImportError:
    Image = None


def png_size(p: Path):
    """Read dimensions from the file header without loading the image."""
    try:
        with Image.open(p) as im:
            return im.width, im.height, im.mode
    except Exception:                                           # noqa: BLE001
        return None


def main() -> int:
    lines = []
    w = lines.append

    w("# Legacy fallback asset inventory")
    w("")
    w("> Generated by `tools/build_asset_manifest.py`. **Do not hand-edit** —")
    w("> regenerate with `python3 tools/build_asset_manifest.py`.")
    w("> This inventories the older canvas fallback and retained reference images.")
    w("")
    w("The primary game now renders live 3D models with vendored Three.js.")
    w("For current asset mapping read [`assets/models/manifest.json`](assets/models/manifest.json),")
    w("[`docs/ASSET-SELECTION.md`](docs/ASSET-SELECTION.md), and")
    w("[`MINIMAX-HANDOFF.md`](MINIMAX-HANDOFF.md). All shipped model dependencies")
    w("and licences are included; the external library is not needed to play.")
    w("Do not regenerate artwork or rerun imports for an as-is migration.")
    w("")

    # ---- loading contract -------------------------------------------------
    w("## Load order is load-bearing")
    w("")
    w("Classic simulation/fallback scripts load in this order and must not be reordered.")
    w("There is no build step. Serve over HTTP for the native 3D modules and glTF files.")
    w("")
    html = (ROOT / "index.html").read_text()
    classic, native = [], []
    for tag in re.finditer(r'<script\b([^>]*)>', html):
        src = re.search(r'\bsrc=["\']([^"\']+)["\']', tag.group(1))
        if src:
            target = native if re.search(r'\btype=["\']module["\']', tag.group(1)) else classic
            target.append(src.group(1))
    for i, source in enumerate(classic, 1):
        w("  %d. `%s`" % (i, source))
    w("")
    w("Classic module additions must also update the `MODULES` list in `tools/playtest.py`.")
    w("Native WebGL modules are separate from that classic headless bundle:")
    for source in native:
        w("- `%s`" % source)
    w("")

    # ---- rendering --------------------------------------------------------
    main_js = (ROOT / "src/main.js").read_text()
    ctx = re.search(r'getContext\(["\']([^"\']+)["\']\)', main_js)
    w("## Legacy fallback rendering")
    w("")
    w("  context : `getContext(\"%s\")`" % (ctx.group(1) if ctx else "?"))
    w("  dpr     : device-pixel-ratio scaled transform (see src/main.js)")
    w("")
    w("`Iso.projectS()` belongs to the canvas fallback. The primary scene is")
    w("`src/render/world3d.js`, which loads glTF/GLB through the included Three.js loader.")
    w("For static renderer evidence, run:")
    w("")
    w("```")
    w("python3 tools/gamekit-agent/gamekit.py doctor .")
    w("```")
    w("")

    # ---- roster sprites ---------------------------------------------------
    w("## Legacy roster sprites — 24 characters")
    w("")
    man = json.loads((ROOT / "src/sprites/manifest.json").read_text())
    w("| id | file | size | alpha |")
    w("|---|---|---|---|")
    for e in man.get("characters24", []):
        p = ROOT / "assets/characters" / e["file"]
        info = png_size(p) if Image else None
        if info:
            w("| `%s` | `%s` | %dx%d | %s |"
              % (e["id"], e["file"], info[0], info[1],
                 "yes" if "A" in info[2] or info[2] == "RGBA" else "no"))
        else:
            w("| `%s` | `%s` | — | — |" % (e["id"], e["file"]))
    w("")
    w("These transparent WebP assets support the fallback. `drawH` controls frame")
    w("height; visible character height also depends on the crop and alpha bounds.")
    w("The retained rebuild command is for legacy maintenance, not this migration:")
    w("")
    w("```")
    w("python3 tools/build_character_pngs.py")
    w("```")
    w("")

    # ---- animated sheets --------------------------------------------------
    anim = man.get("characters", {})
    if anim:
        w("## Animated sheets")
        w("")
        w("| set | animations | frames | file |")
        w("|---|---|---|---|")
        for name, spec in anim.items():
            for aname, s in spec.items():
                p = ROOT / "src/sprites" / name / s.get("file", "")
                fr = s.get("frames") or s.get("frameCount") or "?"
                w("| %s | %s | %s | `%s` |"
                  % (name, aname, fr, s.get("file", "?")))
        w("")

    # ---- stage art --------------------------------------------------------
    art = sorted((ROOT / "art").glob("*.png"))
    if art:
        w("## Stage reference art")
        w("")
        w("Retained mock, stage and browser reference images. `tools/render_art.py`")
        w("produces stage mocks; current reviewed 3D baselines are in `docs/verification/library-3d/`.")
        w("")
        for p in art:
            info = png_size(p) if Image else None
            if info:
                w("  %-34s %dx%d" % (p.name, info[0], info[1]))
        w("")

    # ---- hazards ----------------------------------------------------------
    w("## Legacy procedural hazard art")
    w("")
    w("`src/hazards.js` owns hazard kinds and collision. `src/render/scene.js`")
    w("draws the canvas fallback; `src/render/world3d.js` uses the selected models.")
    w("New kinds need consistent simulation, model-manifest and fallback support.")
    w("")

    # ---- where art comes from --------------------------------------------
    w("## Where to get more art")
    w("")
    w("An existing external library can be configured for optional asset discovery.")
    w("See `tools/gamekit-agent/QUICKSTART.md`; it is not a game runtime dependency.")
    w("")
    w("```")
    w("python3 tools/gamekit-agent/gamekit.py status")
    w("python3 tools/gamekit-agent/gamekit.py search tree")
    w("```")
    w("")
    w("**Licensing:** library records can be unverified; check each selected file.")
    w("The shipped 3D selection retains CC0/MIT notices in `assets/models/licenses/`")
    w("and per-file hashes/source evidence in `assets/models/provenance.json`.")
    w("")
    w("**Do not generate placeholder art** when the library holds something")
    w("suitable. Report \"not in library\" instead — that is a better outcome than")
    w("a pretty wrong answer.")
    w("")

    # ---- verification -----------------------------------------------------
    w("## Before you commit")
    w("")
    w("```")
    w("bash tools/run_all.sh")
    w("python3 tools/playtest.py 10 --seed 12345")
    w("```")
    w("")
    w("Requires `RESULT: NO ERRORS`, `24/24` sprites resolved, `main.js booted`,")
    w("and a **non-zero** forward-only clear rate. A zero there means a lane has")
    w("become unclearable.")
    w("Real browser inspection separately verifies 3D lighting, clipping and animation.")
    w("")

    OUT.write_text("\n".join(lines) + "\n")
    print("wrote %s (%d lines)" % (OUT, len(lines)))
    return 0


if __name__ == "__main__":
    sys.exit(main())
